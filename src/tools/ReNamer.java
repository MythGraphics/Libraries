    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        init();
        String[] fs;                                                                                // FileStrings
        fs = path.list();
        for (int i = 0; i < fs.length; ++i) {
            if ( fs[i].contains(".") && fs[i].contains(filter) ) {
                jTextArea1.append( fs[i] + "\n");
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        File f;
        File[] files = path.listFiles();
        try { for (int i = 0; i < files.length; ++i) {
            if ( files[i].getName().contains(".") && files[i].getName().contains(filter) ) {
                f = getNewFile( files[i].getCanonicalPath(), filter );
                if (( f != null ) && files[i].renameTo(f) ) {
                    jTextArea1.append( files[i].getName() + "\n > " + f.getName() + " \u221A" + "\n" );
                } else {
                    jTextArea1.append( files[i].getName() + "\n > " + f.getName() + " X" + "\n" );
        }}}}
        catch (IOException e) { jTextArea1.append("\n" + e.getMessage() + "\n" ); }
        jButton2.setEnabled(false);
    }//GEN-LAST:event_jButton2ActionPerformed

