    private File getNewFile(String old, String filter) {
        String ending = old.substring( old.lastIndexOf(".") );
        String s = old.substring( 0, old.lastIndexOf(filter) );
        s += ending;
        File f = new File(s);
        if ( f.exists() ) {
            return null;
        } else {
            return f;
        }
    }

    private void init() {
        path = new File( pathField1.getText() );
        if ( !path.exists() || !path.isDirectory() ) {
            pathField1.setBackground( ColorLibrary.LIGHT_RED );
            return;
        }
        pathField1.setBackground( ColorLibrary.LIGHT_GREEN );

        filter = filterField1.getText();
        jTextArea1.setText("");
        jButton2.setEnabled(true);
    }

